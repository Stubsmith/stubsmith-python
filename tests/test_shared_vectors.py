"""
Shared vectors: run every case of the masking and fail-closed vector files.

The files in tests/vectors/ are generated by tools/gen_shared_vectors.py from the
Python SDK and are the contract any other SDK has to meet. Each case names an
operation (see tests/shared_vector_ops.py and the file's description) and
carries an input and the exact expected result.

If a vector exposes a mismatch, the vectors are wrong or the SDK regressed -
the Python implementation is the source of truth. Regenerate with
``python3 tools/gen_shared_vectors.py`` only for a change that is meant.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

import pytest

from tests.shared_vector_ops import expand, run_op

_DIR = Path(__file__).parent / "vectors"
_FILES = (
    "masking-vectors.json",
    "masking-pipeline-vectors.json",
    "masking-values-vectors.json",
    "fail-closed-vectors.json",
)


def _load() -> List[Tuple[str, Dict[str, Any]]]:
    out = []
    for name in _FILES:
        with open(_DIR / name, encoding="utf-8") as f:
            for case in json.load(f)["cases"]:
                out.append((name, case))
    return out


_CASES = _load()


def _text(value: Any) -> str:
    # Strict about types: 1, 1.0 and True are different values here.
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


@pytest.mark.parametrize("file, case", _CASES, ids=[case["name"] for _, case in _CASES])
def test_shared_vector(file: str, case: Dict[str, Any]) -> None:
    actual = run_op(case["op"], expand(case["input"]))
    assert _text(actual) == _text(expand(case["expected"])), f'{file}: {case["name"]}'


def test_case_names_are_unique() -> None:
    names = [case["name"] for _, case in _CASES]
    assert len(names) == len(set(names))


def test_files_are_what_the_generator_produces() -> None:
    """A vector edited by hand, or an SDK change that was not regenerated, fails here."""
    import importlib.util

    path = Path(__file__).parent.parent / "tools" / "gen_shared_vectors.py"
    spec = importlib.util.spec_from_file_location("gen_shared_vectors", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name, text in module.build().items():
        committed = (_DIR / name).read_bytes().decode("utf-8")
        assert committed == text, f"{name} differs from tools/gen_shared_vectors.py output; regenerate it"
